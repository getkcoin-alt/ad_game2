// Offline level balancing. A greedy bot plays every level many times with unlimited moves and
// records how many moves it needed. Each level's move budget is then set to the quantile that
// gives the target win rate, and star thresholds come from the same distribution.
//
//   node tools/balance.mjs            → prints the report and rewrites www/js/engine/tuning.js
//   node tools/balance.mjs --dry      → report only
//   node tools/balance.mjs --sims 80  → more simulations per level

import { writeFileSync } from 'node:fs';
import { buildLevel, difficultyOf, TOTAL_LEVELS } from '../www/js/engine/levels.js';
import { GameSession } from '../www/js/game/session.js';
import { SP } from '../www/js/engine/board.js';

const args = process.argv.slice(2);
const DRY = args.includes('--dry');
const SIMS = Number(args[args.indexOf('--sims') + 1]) || 50;

export function evaluateMove(session, a, b) {
  const board = session.board;
  const ta = board.tiles[a[0]][a[1]], tb = board.tiles[b[0]][b[1]];
  if (ta.special && tb.special) return 120;
  if (ta.special === SP.DABBA || tb.special === SP.DABBA) {
    const other = ta.special === SP.DABBA ? tb : ta;
    return 60 + (session.neededColors().includes(other.color) ? 40 : 0);
  }
  board.tiles[a[0]][a[1]] = tb; board.tiles[b[0]][b[1]] = ta;
  const groups = board.findGroups();
  board.tiles[a[0]][a[1]] = ta; board.tiles[b[0]][b[1]] = tb;
  const needed = new Set(session.neededColors());
  let score = 0;
  for (const g of groups) {
    score += g.cells.length;
    if (needed.has(g.color)) score += g.cells.length * 4;
    if (g.maxRun >= 5) score += 50; else if (g.hasH && g.hasV) score += 30; else if (g.maxRun === 4) score += 18;
    for (const [r, c] of g.cells) {
      const t = board.tiles[r][c];
      if (t && t.special) score += 25;
      if (board.lock[r][c]) score += 10;
      for (const [dr, dc] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) if (board.isPlayable(r + dr, c + dc) && board.dough[r + dr][c + dc]) score += 6;
    }
    // prefer lower matches (more cascades)
    score += Math.max(...g.cells.map(([r]) => r)) * 0.3;
  }
  return score;
}

export function botPlay(level, seedOffset, maxMoves = 120) {
  const s = new GameSession(level, { seedOffset });
  s.movesLeft = maxMoves;
  while (s.state === 'playing') {
    if (s.tadkaReady()) s.useTadka();
    if (s.state !== 'playing') break;
    const moves = s.board.listMoves();
    let best = null, bestScore = -1;
    for (const [a, b] of moves) {
      const sc = evaluateMove(s, a, b) + (s.board.rng() * 0.5);
      if (sc > bestScore) { bestScore = sc; best = [a, b]; }
    }
    s.swap(best[0], best[1]);
  }
  return s.state === 'won' ? s.movesUsed : Infinity;
}

const quantile = (sorted, q) => sorted[Math.min(sorted.length - 1, Math.max(0, Math.ceil(q * sorted.length) - 1))];

export function targetWinRate(n) {
  const stage = (n - 1) % 6;
  let t = 0.98 - 0.33 * difficultyOf(n);
  if (n <= 6) t = 0.99;
  if (stage === 3) t += 0.04;
  return Math.min(0.99, t);
}

function main() {
  const tuning = {};
  const rows = [];
  const t0 = Date.now();
  for (let n = 1; n <= TOTAL_LEVELS; n++) {
    const level = buildLevel(n);
    const needed = [];
    for (let i = 0; i < SIMS; i++) needed.push(botPlay(level, 1000 + i));
    needed.sort((a, b) => a - b);
    const target = targetWinRate(n);
    // humans are less precise than the bot early on: give beginners a cushion
    const cushion = n <= 10 ? 3 : n <= 25 ? 2 : 1;
    const moves = Math.max(10, Math.min(45, quantile(needed, target) + cushion));
    const median = quantile(needed, 0.5);
    const fast = quantile(needed, 0.2);
    const s2 = Math.max(2, moves - median);
    const s3 = Math.max(s2 + 2, moves - fast);
    tuning[n] = [moves, s2, s3];
    const winRate = needed.filter((x) => x <= moves - cushion).length / SIMS;
    rows.push({ n, moves, s2, s3, median, botWin: winRate.toFixed(2), target: target.toFixed(2), colors: level.colors, dishes: level.dishes.length });
  }
  console.table(rows);
  console.log(`balanced ${TOTAL_LEVELS} levels × ${SIMS} sims in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  if (!DRY) {
    const body = Object.entries(tuning).map(([n, v]) => `  ${n}: [${v.join(', ')}],`).join('\n');
    writeFileSync(new URL('../www/js/engine/tuning.js', import.meta.url),
      `// Generated by tools/balance.mjs — [moves, movesLeftFor2Stars, movesLeftFor3Stars] per level.\n// Re-run \`npm run balance\` after changing level generation.\nexport const TUNING = {\n${body}\n};\n`);
    console.log('wrote www/js/engine/tuning.js');
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
